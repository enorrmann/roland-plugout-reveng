"""Generate qmask.h: for each biased exponent field of a double, the mask of the bits quant() keeps (dspcore.h).

    python3 examples/from_scratch/emu/gen_qmask.py

k = 20 + 4s - E low bits are cleared (s = clamp((E + 7) >> 2, 0, 3), E = unbiased exponent); k > 52 -> 63 (a signed
zero); E >= 9 (|v| >= 512, inf, nan) -> nothing cleared. test_core.py test_quant checks quant against quant_ref.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def mask(ebits):
    e = ebits - 1023
    s = min(3, max(0, (e + 7) >> 2))
    k = 20 + 4 * s - e
    k = 0 if k < 0 or e >= 9 else 63 if k > 52 else k
    return ~((1 << k) - 1) & 0xFFFFFFFFFFFFFFFF


def main():
    rows = [', '.join('0x%016xu' % mask(i + j) for j in range(4)) for i in range(0, 2048, 4)]
    open(os.path.join(HERE, 'qmask.h'), 'w').write(
        '/* generated by gen_qmask.py: for each biased exponent field (bits 62..52 of a double) the mask of the bits\n'
        ' * quant() keeps (dspcore.h) */\nstatic const uint64_t QMASK[2048] = {\n    ' + ',\n    '.join(rows) + '\n};\n')


if __name__ == '__main__':
    main()
