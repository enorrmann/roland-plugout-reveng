"""programs.h for mini.c: the empty slot program and our voice (../dsp/voice.hex, from make_voice.py).

    python3 gen_programs.py <outdir>
Words are packed as engine.c expects them: two 16-bit words per 32-bit word, the first one in the high half.
"""
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
out = sys.argv[1]
words = [int(t, 16) for line in open(os.path.join(HERE, '..', 'dsp', 'voice.hex'))
         for t in line.split('#')[0].split()]
nbytes = 2 * len(words)
w = words + [0] * (len(words) & 1)
packed = [(w[i] << 16) | w[i + 1] for i in range(0, len(w), 2)]
L = ['/* generated by mini/gen_programs.py: our own DSP microcode (dsp/voice.s) and the empty program */',
     '#include <stdint.h>',
     'static const uint32_t mc_empty[4] = { 0x0a02ff70, 0x0a02ff70, 0x0b0200f8, 0x00010000 };',
     '#define MC_VOICE_BYTES %#x' % nbytes,
     'static const uint32_t mc_VOICE[%d] __attribute__((aligned(4))) = {' % len(packed)]
for i in range(0, len(packed), 8):
    L.append('  ' + ', '.join('0x%08x' % x for x in packed[i:i + 8]) + ',')
L.append('};')
if os.environ.get('ROLAND_MAIN'):        # diagnostic only: Roland's main programs of all DSPs (engine build)
    src = open(os.path.join(HERE, '..', 'engine', 'build', 'programs.h')).read()
    import re
    for n in ('MAIN0', 'MAIN1', 'MAIN2', 'MAIN3', 'MAIN4', 'MAIN5'):
        m = re.search(r'static const uint32_t mc_%s\[\d+\].*?\};\n#define MC_%s_BYTES 0x[0-9a-f]+\n' % (n, n), src, re.S)
        assert m, n
        L.append(m.group(0))
os.makedirs(out, exist_ok=True)
open(os.path.join(out, 'programs.h'), 'w').write('\n'.join(L) + '\n')
print('programs.h: voice %d words (%d bytes), empty program' % (len(words), nbytes))
