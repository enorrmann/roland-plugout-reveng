"""DSP programs for the engine: the only foreign data of the PLUG-OUT.

    python3 programs.py plugins/JX-3P outdir      -> outdir/programs.h

The microcode (main program of each DSP, oscillator and effect slot programs)
is copied from the user's own JX-3P PLUG-OUT at build time: region 1 of
Script/Code8_1.Dat is unpacked and each program is cut out at its offset and
checked against its SHA-256. Nothing is executed; nothing of it is stored in
the repository. The empty slot program and the (all zero) data blocks are ours (engine.c).
"""
import hashlib, os, struct, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..', '..', '..')
BASE = 0x60A00000          # run address of region 1 in Code8_1.Dat (slot 1)

# name: (bytes, run address in the JX-3P 1.01 image, sha256[:16]); DSP2 and DSP3
# get the same oscillator programs, so one copy each
MICROCODE = {
    'main0': (0x13ca, 0x60a15270, '01a5adab95df3ef2'),
    'main1': (0x139a, 0x60a16918, '61798b4801a2592e'),
    'main2': (0x814, 0x60a17cd4, '59ede74e41c0ab68'),
    'main3': (0x7e2, 0x60a18520, 'f24d2ed902a5c56a'),
    'main4': (0x1436, 0x60a18d3c, '9cb9f43b70d40325'),
    'main5': (0x1398, 0x60a1a1c4, 'e90295901cae2255'),
    'dco1_saw': (0x1008, 0x60a1b594, 'd54b9f85a1bde4cc'),   # SAW and PULSE (flag B2:0x2a)
    'dco2_saw': (0x1008, 0x60a1c59c, '77dcd06a81f01039'),
    'dco1_sqr': (0xf88, 0x60a1d5f4, 'a0d8a46347e0b90f'),
    'dco2_sqr': (0xf88, 0x60a1e57c, '838886f1f7e59ef5'),
    'dco2_noise': (0x180, 0x60a1f554, 'bf4bbddd08e0fcce'),
    'fx_od': (0x302, 0x60a23864, '398f40d99f0f5785'),
    'fx_ds': (0x2d2, 0x60a23b90, '859fce7013baf4fb'),
    'fx_ch': (0xc2c, 0x60a24bc8, 'f361f7a38b4417e1'),
    'fx_fz': (0x41e, 0x60a23e8c, '1e2e5624b3889022'),
    'fx_cr': (0x3d0, 0x60a242d4, '8e1c050657a5656f'),
    'fx_ph': (0x4d4, 0x60a246cc, '64dc7d93bd4c0aad'),
}


# our own oscillator programs (text files generated by re/dspasm.py), added to the JX-3P set;
# OWN_PROGS=name=file,... adds more (paths relative to re/dspexp/own or absolute), e.g. the wavetable build
OWN = {'dco1_fold': 'fold_dco1.txt'}
OWN.update(t.split('=', 1) for t in os.environ.get('OWN_PROGS', '').split(',') if t)


def unpack(plugin, out):
    proj = os.path.join(out, 'jx')
    if not os.path.exists(os.path.join(proj, 'region1.bin')):
        subprocess.run([sys.executable, os.path.join(ROOT, 'tools', 'plugout_build.py'), 'unpack',
                        os.path.join(plugin, 'Script', 'Code8_1.Dat'), proj], check=True,
                       stdout=subprocess.DEVNULL)
    return open(os.path.join(proj, 'region1.bin'), 'rb').read()


def test_blob(path):
    """hex words in execution order (text, '#' comments) -> (blob, bytes); see re/dspasm.py"""
    w = [int(t, 16) for line in open(path) for t in line.split('#')[0].split()]
    n = 2 * len(w)
    w += [0] * (len(w) & 1)
    return struct.pack('<%dI' % (len(w) // 2), *(w[i] << 16 | w[i + 1] for i in range(0, len(w), 2))), n


# Patches over Roland's MAIN0/MAIN1. Each site is one instruction `r0 = r1` (1703 0041 1f10, three words, index in
# execution order) that copies an envelope into r0; it is replaced by a same-size instruction, so the jumps do not move.
#   ENV-2 (amplitude) -> the note gate of the voice (A022 voice A, A034 voice B): the VCA opens with the key.
#   ENV-1 (filter)    -> 0: no envelope modulation of the filter (r0 = #0, 0903 0050 0000).
GATE_OLD = [0x1703, 0x0041, 0x1f10]
PATCH_SITES = {
    'main0': ((946, [0x0903, 0x0050, 0x0000]), (1196, [0x0c03, 0x0fe0, 0xa022]),
              (2128, [0x0903, 0x0050, 0x0000]), (2378, [0x0c03, 0x0fe0, 0xa034])),
    'main1': ((991, [0x0903, 0x0050, 0x0000]), (1241, [0x0c03, 0x0fe0, 0xa022]),
              (2173, [0x0903, 0x0050, 0x0000]), (2423, [0x0c03, 0x0fe0, 0xa034])),
}


def patch_main(name, blob):
    """blob (memory order) of a main program -> the same blob with its envelope sites replaced"""
    sites = PATCH_SITES.get(name)
    if not sites:
        return blob
    h = struct.unpack('<%dH' % (len(blob) // 2), blob)
    w = []
    for i in range(0, len(h), 2):           # execution order: upper half of each LE word first
        w += [h[i + 1], h[i]]
    for pos, new in sites:
        if w[pos:pos + 3] != GATE_OLD:
            raise SystemExit(f'{name}: word {pos} is {w[pos:pos + 3]}, not the envelope output: wrong program')
        w[pos:pos + 3] = new
    out = struct.pack('<%dI' % (len(w) // 2), *(w[i] << 16 | w[i + 1] for i in range(0, len(w), 2)))
    assert len(out) == len(blob)
    return out


def main(plugin, out):
    os.makedirs(out, exist_ok=True)
    img = unpack(plugin, out)
    L = ['/* generated by programs.py: DSP microcode copied from the JX-3P at build time; do not commit */',
         '#include <stdint.h>']
    # ISA test bench (re/dspaudio.py): MC_TEST=prefix=file,...  replaces every program whose
    # name starts with prefix (dco1_, dco2_saw, fx_ ...); a bare file = MC_TEST_SLOT (default fx)
    test = [t.split('=') if '=' in t else (os.environ.get('MC_TEST_SLOT', 'fx') + '_', t)
            for t in os.environ.get('MC_TEST', '').split(',') if t]
    for name, (n, addr, sha) in MICROCODE.items():
        nb = (n + 3) & ~3                  # 4n+2 blobs end with the word holding the final 0x0001
        blob = img[addr - BASE: addr - BASE + nb]
        got = hashlib.sha256(blob).hexdigest()[:16]
        if got != sha:
            raise SystemExit(f'{name}: sha256 {got} != {sha}: not the JX-3P 1.01 PLUG-OUT?')
        blob = patch_main(name, blob)
        for prefix, path in test:
            if name.startswith(prefix):
                blob, n = test_blob(path)
                nb = len(blob)
        w = struct.unpack('<%dI' % (nb // 4), blob)
        L.append(f'static const uint32_t mc_{name.upper()}[{len(w)}] __attribute__((aligned(4))) = {{')
        for i in range(0, len(w), 8):
            L.append('  ' + ', '.join(f'0x{x:08x}' for x in w[i:i + 8]) + ',')
        L.append('};')
        L.append(f'#define MC_{name.upper()}_BYTES {n:#x}')
    # our own programs (not replacements): re/dspexp/own/<name>.txt for every name in OWN, emitted as mc_<NAME>
    for name, fname in OWN.items():
        path = os.path.join(HERE, '..', 're', 'dspexp', 'own', fname)
        blob, n = test_blob(path)
        w = struct.unpack('<%dI' % (len(blob) // 4), blob)
        L.append(f'/* own program {fname} (re/dspasm.py) */')
        L.append(f'static const uint32_t mc_{name.upper()}[{len(w)}] __attribute__((aligned(4))) = {{')
        for i in range(0, len(w), 8):
            L.append('  ' + ', '.join(f'0x{x:08x}' for x in w[i:i + 8]) + ',')
        L.append('};')
        L.append(f'#define MC_{name.upper()}_BYTES {n:#x}')
    if test:                               # test programs t0 (DSP2) and t1 (DSP3), DCO2 slot (engine.c DSPTEST)
        mute = struct.pack('<5I', 0x0a02ff70, 0x09030050, 0x00007809, 0x8fe08fe2, 0x8fe48fe6) + \
            struct.pack('<4I', 0x2221221d, 0x22292225, 0x0a02ff70, 0x0b0200f8) + struct.pack('<I', 0x00010000)
        tests = dict(test)
        for k in range(2):
            blob, n = test_blob(tests[f't{k}']) if f't{k}' in tests else (mute, 0x26)
            w = struct.unpack('<%dI' % (len(blob) // 4), blob)
            L.append(f'static const uint32_t mc_T{k}[{len(w)}] __attribute__((aligned(4))) = {{')
            L.append('  ' + ', '.join(f'0x{x:08x}' for x in w) + ',')
            L.append('};')
            L.append(f'#define MC_T{k}_BYTES {n:#x}')
    with open(os.path.join(out, 'programs.h'), 'w') as f:
        f.write('\n'.join(L) + '\n')
    print(f'programs.h: {len(MICROCODE)} programs, {sum((n + 3) & ~3 for n, _, _ in MICROCODE.values())} bytes')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
