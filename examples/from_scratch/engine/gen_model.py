"""Compile the parameter model (model_spec.py) into build/model.h for engine.c.

    python3 gen_model.py outdir
"""
import os, struct, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import model_spec as M
from expr import OP, E, f32

NONE = 0xFFFF


def group(pid):
    """OS parameter group of an id (the slave's +0x00 get takes it)"""
    for g, top in enumerate((0x225, 0x3ED, 0x519, 0x6CD, 0x74D)):
        if pid < top:
            return g
    return 5


def target(t):
    bank = t[0] == 'B'
    dsp, rest = t[1:].split(':')
    if '/' in rest:
        idt, rf = rest.split('/')
        ramp, flag = rf[1:].split('f')
        ramp, flag = int(ramp), int(flag)
    else:
        idt, ramp, flag = rest, 0xFF, 0
    return (1 if bank else 0, int(dsp), int(idt, 16), ramp, flag)


def depth(code):
    """maximum stack depth of postfix code"""
    d = mx = 0
    i = 0
    ar = {OP[o]: n for o, n in (('add', 2), ('sub', 2), ('mul', 2), ('div', 2), ('min', 2), ('max', 2),
                                  ('ge', 2), ('lt', 2), ('sel', 3), ('exp2', 1), ('abs', 1), ('floor', 1))}
    while i < len(code):
        op = code[i]
        if op in (OP['const'], OP['param'], OP['fparam']):
            d += 1; i += 2
        elif op == OP['slave']:
            d += 1; i += 1
        elif op == OP['pick']:
            d -= code[i + 1]; i += 2
        elif op == OP['interp']:
            i += 3
        elif op == OP['knots']:
            i += 5
        else:
            d -= ar[op] - 1; i += 1
        mx = max(mx, d)
    return mx


def main(out):
    os.makedirs(out, exist_ok=True)
    ids = set(M.REFRESH_ORDER)
    for src, targets, e, when in M.OUT:
        if src is not None:
            ids.add(src)
        ids |= e.params() | (when.params() if when is not None else set())
    ids = sorted(ids)
    idx = {p: i for i, p in enumerate(ids)}
    consts, code = [], []
    # outputs grouped by source (spec order kept within a source), start-up constants first
    order = [None] + ids
    outs, tgts = [], []
    first = {}

    def emit(e):
        c = e.code(consts)
        # param operands: id -> index
        i = 0
        while i < len(c):
            if c[i] in (OP['param'], OP['fparam']):
                c[i + 1] = idx[c[i + 1]]
            i += {OP['const']: 2, OP['param']: 2, OP['fparam']: 2, OP['pick']: 2, OP['interp']: 3, OP['knots']: 5}.get(c[i], 1)
        assert depth(c) <= 16, depth(c)
        off = len(code)
        code.extend(c)
        return off, len(c)

    for src in order:
        first[src] = len(outs)
        for s, targets, e, when in M.OUT:
            if s != src:
                continue
            w = emit(when) if when is not None else (NONE, 0)
            x = emit(e)
            outs.append((NONE if s is None else idx[s], w[0], w[1], x[0], x[1], len(tgts), len(targets)))
            tgts.extend(target(t) for t in targets)
    counts = {src: (first[src], sum(1 for o in outs[first[src]:] if o[0] == (NONE if src is None else idx[src]))) for src in order}
    vel = [0.0] + [M.curve('vel', E('const', float(v)), 0).ev({}, 0) if v else 0 for v in range(1, 128)]
    vel = [f32(2 ** M.interp(E('const', float(v)), M.K['vel'], M.XS_VEL).ev({}, 0)) if v else 0.0 for v in range(128)]
    L = ['/* generated by gen_model.py from model_spec.py */', '#include <stdint.h>',
         f'#define NPARAM {len(ids)}', f'#define NOUT {len(outs)}', f'#define NTGT {len(tgts)}']
    L.append('static const uint16_t param_id[NPARAM] = {' + ', '.join(f'{p:#x}' for p in ids) + '};')
    L.append('static const uint8_t param_group[NPARAM] = {' + ', '.join(str(group(p)) for p in ids) + '};')
    L.append(f'static const float mconst[{max(1, len(consts))}] = {{' +
             ', '.join(repr(f32(c)) + 'f' if '.' in repr(f32(c)) or 'e' in repr(f32(c)) else repr(f32(c)) + '.0f'
                       for c in consts) + '};')
    L.append(f'static const uint16_t mcode[{len(code)}] = {{')
    for i in range(0, len(code), 16):
        L.append('  ' + ', '.join(str(c) for c in code[i:i + 16]) + ',')
    L.append('};')
    L.append('static const mout_t mout[NOUT] = {')
    L += [f'  {{{s}, {wo}, {wn}, {xo}, {xn}, {t0}, {nt}}},' for s, wo, wn, xo, xn, t0, nt in outs]
    L.append('};')
    L.append('static const mtgt_t mtgt[NTGT] = {')
    L += [f'  {{{b}, {d}, {r}, {f}, {i:#x}}},' for b, d, i, r, f in tgts]
    L.append('};')
    L.append('static const uint16_t src_first[NPARAM] = {' + ', '.join(str(counts[p][0]) for p in ids) + '};')
    L.append('static const uint16_t src_count[NPARAM] = {' + ', '.join(str(counts[p][1]) for p in ids) + '};')
    L.append(f'#define CONST_FIRST {counts[None][0]}')
    L.append(f'#define CONST_COUNT {counts[None][1]}')
    L.append(f'static const uint16_t refresh_order[{len(M.REFRESH_ORDER)}] = {{' +
             ', '.join(str(idx[p]) for p in M.REFRESH_ORDER) + '};')
    L.append('static const float vel_curve[128] = {' + ', '.join(repr(v) + 'f' if '.' in repr(v) or 'e' in repr(v)
                                                              else repr(v) + '.0f' for v in vel) + '};')
    for name in ('ASSIGN_PARAM_IDS',):
        pass
    for k, v in (('P_DCO1_WAVE', 0x6d4), ('P_DCO2_WAVE', 0x6d9), ('P_FX_TYPE', 0x748)):
        L.append(f'#define {k} {idx[v]}')
    with open(os.path.join(out, 'model.h'), 'w') as f:
        f.write('\n'.join(L) + '\n')
    print(f'model.h: {len(ids)} parameters, {len(outs)} outputs, {len(tgts)} DSP writes, '
          f'{len(code)} code words, {len(consts)} constants')


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, 'build'))
