#!/bin/sh
# make_waves.sh: the JP-08 PLUG-OUT with OSC1 / OSC2 WAVE (README.md §12): one s1cc kernel per wave pair (waves/*.c:
# bq_arm.c with BQ_OSC1 / BQ_OSC2), built into sdk/s1cc/build/bq_jp08w<o1><o2>, then SYSTEM-S1CC-BOUTIQUE
# build_multi.sh SECT_SWITCH=1: moving a WAVE knob places that pair's voice sections (FC40), as the stock synth.
#   sh sdk/s1cc/examples/boutique_ported/tools/make_waves.sh [NAME]        (default NAME=JP-08-S1W)
# Positions (JP-08, tools/bq_fw.py setp 0x19D / 0x1A1): OSC1 0 sine, 1 triangle, 2 saw, 3 pulse, 4 square, 5 noise
# (ours, not Roland's); OSC2 0 sine, 1 saw, 2 pulse, 3..5 the same in LOW (C055 = 1; LOW itself not implemented)
set -e
HERE=$(cd "$(dirname "$0")/.." && pwd)
ROOT=$(cd "$HERE/../../../.." && pwd)
NAME=${1:-JP-08-S1W}
cd "$ROOT"
for a in 0 1 2 3 4 5; do for b in 0 1 2; do
    f=$HERE/waves/bq_arm_w$a$b.c
    printf '/* JP-08 wave pair OSC1 %s, OSC2 %s (README.md §12); generated by tools/make_waves.sh */\n#define BQ_OSC1 %s\n#define BQ_OSC2 %s\n#include "../bq_arm.c"\n' $a $b $a $b > "$f"
done; done
# the kernels, three at a time
for a in 0 1 2 3 4 5; do
    for b in 0 1 2; do
        sdk/s1cc/s1cc build "$HERE/waves/bq_arm_w$a$b.c" -o sdk/s1cc/build/bq_jp08w$a$b > sdk/s1cc/build/bq_jp08w$a$b.log 2>&1 &
    done
    wait
    for b in 0 1 2; do echo "w$a$b: $(grep -E '^DSP' sdk/s1cc/build/bq_jp08w$a$b.log | tr '\n' ' ')"; done
done
# the map: OSC2 positions 3..5 = 0..2 (the JP-08's LOW versions of 0..2: LOW not implemented, README.md §12)
K="sdk/s1cc/build/bq_jp08w22"
for a in 0 1 2 3 4 5; do for b in 0 1 2 3 4 5; do
    K="$K $a,$b:sdk/s1cc/build/bq_jp08w$a$((b % 3))"
done; done
# MOD_DSP=B: every pair puts the pitch envelope and COLOR MOD on DSP B (auto chose per kernel: other host addresses)
MOD_DSP=B PANEL=sdk/s1cc/examples/boutique_ported/bq_arm.panel KV_WORDS=${KV_WORDS:-} SECT_SWITCH=1 KERNELS="$K" NAME=$NAME sh examples/system_s1cc_boutique/build_multi.sh
