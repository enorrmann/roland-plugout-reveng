#!/bin/sh
# make_fx.sh: JX-3P-S1-FX = the JX-3P port of sdk/s1cc/examples/jx3p_ported (its 12 wave-pair kernels, unchanged) plus
# the JX-3P CHORUS as SYSTEM-S1CC-BOUTIQUE's master effect (FX_KERNEL, jx3p_fx.c) on the CRUSHER knob (README.md).
# jx3p_ported stays the reference without the effect (its make_waves.sh, its panels).
#   sh sdk/s1cc/examples/jx3p_fx/make_fx.sh [NAME]          (default NAME=JX-3P-S1-FX)
#   ONE_PAIR=1 sh ...: only the SAW / SAW pair (test builds: fast)
#   FX_WET=1.5 FX_DRY=0.7 FX_DEPTH=1.5 FX_RATE=1 sh ...: the effect's build parameters (jx3p_fx.c JXF_*; 1 = Roland's)
# Needs the pair kernels built by jx3p_ported/tools/make_waves.sh (sdk/s1cc/build/jx3p_wAB).
set -e
HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/../../../.." && pwd)
NAME=${1:-JX-3P-S1-FX}
cd "$ROOT"
# FX_WET / FX_DRY / FX_DEPTH / FX_RATE (jx3p_fx.c JXF_*, README.md "Build parameters"; unset = 1, Roland's): a
# wrapper with their #defines around jx3p_fx.c (as make_waves.sh makes the pairs)
src="$HERE/jx3p_fx.c"
if [ -n "$FX_WET$FX_DRY$FX_DEPTH$FX_RATE" ]; then
    mkdir -p sdk/s1cc/build/jx3p_fx_src
    src=sdk/s1cc/build/jx3p_fx_src/jx3p_fx_cfg.c
    {
        echo "/* generated by make_fx.sh: jx3p_fx.c with FX_WET=${FX_WET:-1} FX_DRY=${FX_DRY:-1} FX_DEPTH=${FX_DEPTH:-1} FX_RATE=${FX_RATE:-1} */"
        [ -n "$FX_WET" ] && echo "#define JXF_WET (${FX_WET}f)"
        [ -n "$FX_DRY" ] && echo "#define JXF_DRY (${FX_DRY}f)"
        [ -n "$FX_DEPTH" ] && echo "#define JXF_DEPTH (${FX_DEPTH}f)"
        [ -n "$FX_RATE" ] && echo "#define JXF_RATE (${FX_RATE}f)"
        echo "#include \"$HERE/jx3p_fx.c\""
    } > "$src"
    echo "FX: WET ${FX_WET:-1} DRY ${FX_DRY:-1} DEPTH ${FX_DEPTH:-1} RATE ${FX_RATE:-1}"
fi
sdk/s1cc/s1cc build "$src" -o sdk/s1cc/build/jx3p_fx > sdk/s1cc/build/jx3p_fx.log 2>&1 || { cat sdk/s1cc/build/jx3p_fx.log; exit 1; }
grep -E '^DSP' sdk/s1cc/build/jx3p_fx.log
if [ -n "$ONE_PAIR" ]; then
    K="0,0:sdk/s1cc/build/jx3p_w00"                        # SECT_SWITCH needs the pair form (multi.c kmap2)
else
    K="sdk/s1cc/build/jx3p_w00"
    for a in 0 1 2 3 4 5; do for b in 0 1 2 3 4 5; do
        K="$K $a,$b:sdk/s1cc/build/jx3p_w$((a < 2 ? a : 2))$((b < 3 ? b : 3))"
    done; done
fi
for d in $K; do
    d=${d#*:}
    [ -f "$d/voice.s1k" ] || { echo "make_fx.sh: no $d (sh sdk/s1cc/examples/jx3p_ported/tools/make_waves.sh first)" >&2; exit 2; }
done
# as jx3p_ported/tools/make_waves.sh, plus FX_KERNEL and the panel with CRUSHER lit
PATCH_BANK="${PATCH_BANK:-$ROOT/plugins/JX-3P/Patch/1 Preset.bin}" FX_KERNEL=sdk/s1cc/build/jx3p_fx \
SECT_N=2 ARM_WORDS=1 PANEL=sdk/s1cc/examples/jx3p_fx/jx3p_fx_waves.panel KV_WORDS=${KV_WORDS:-} SECT_SWITCH=1 KERNELS="$K" NAME=$NAME sh examples/system_s1cc_boutique/build_multi.sh
