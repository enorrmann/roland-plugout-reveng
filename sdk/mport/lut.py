"""Lookup tables of the Mutable Instruments sources -> what our DSP can run (docs/MUTABLE_SDK.md §4).

The modules read their curves from int16 / uint16 tables in resources.cc (generated by resources/*.py). On our DSP
an audio-rate table read costs an indexed load and a hidden-register set per point; a short polynomial costs a few
fused ops and no memory. So:

  * audio-rate curve (waveshaper, sine): fit_odd() / fit() -> coefficients for Kernel.poly_odd() / horner(), with
    the error in LSB of the original int16 output;
  * control-rate curve (a coefficient that only changes with a knob or the note): evaluate it in Python at build
    time, at every knob value, and give the ARM a float table (as make_synth.py header() does).

    t = lut.table('braids', 'ws_moderate_overdrive')        # list of ints, as in resources.cc
    f = lut.interp88(t)                                     # Braids' Interpolate88 as a function of x in [-1, 1)
    c, err = lut.fit_odd(f, 7, x_max=0.875)                 # odd polynomial of degree 7, err = max |error| (LSB)
"""
import os
import re

import numpy as np

EURORACK = os.environ.get('EURORACK', os.path.expanduser('~/git/eurorack'))

_ARRAY = re.compile(r'const\s+(u?int\d+_t)\s+(\w+)\[\]\s*=\s*\{([^}]*)\}', re.S)
_CACHE = {}


def tables(module):
    """{name: [values]} of every array in <EURORACK>/<module>/resources.cc"""
    if module not in _CACHE:
        src = open(os.path.join(EURORACK, module, 'resources.cc')).read()
        _CACHE[module] = {m.group(2): [int(v, 0) for v in m.group(3).replace('\n', ' ').split(',') if v.strip()]
                          for m in _ARRAY.finditer(src)}
    return _CACHE[module]


def table(module, name):
    return tables(module)[name]


def interp88(t, scale=32768.0):
    """Interpolate88(table, x * 32768 + 32768) / scale as a function of x in [-1, 1) (Braids' waveshapers)"""
    t = np.asarray(t, dtype=float)

    def f(x):
        i = np.clip(np.floor((np.asarray(x) * 32768 + 32768)).astype(np.int64), 0, 65535)
        a, b = t[i >> 8], t[(i >> 8) + 1]
        return (a + np.trunc((b - a) * (i & 0xFF) / 256.0)) / scale
    return f


def interp824(t, scale=32768.0):
    """Interpolate824(table, phase) / scale as a function of phase in [0, 1)"""
    t = np.asarray(t, dtype=float)

    def f(p):
        ph = (np.asarray(p) * 2 ** 32).astype(np.uint64) & 0xFFFFFFFF
        i = (ph >> 24).astype(np.int64)
        a, b = t[i], t[np.minimum(i + 1, len(t) - 1)]
        return (a + np.trunc((b - a) * ((ph >> 8) & 0xFFFF) / 65536.0)) / scale
    return f


def fit_odd(f, degree, x_max=1.0, n=4001, lsb=1 / 32768.0):
    """least-squares odd polynomial a1 x + a3 x^3 + ... of `degree` to f on [-x_max, x_max]; returns
    ((a1, a3, ...), max |error| in LSB)"""
    x = np.linspace(-x_max, x_max, n)
    y = f(x)
    powers = list(range(1, degree + 1, 2))
    A = np.stack([x ** p for p in powers], axis=1)
    c, *_ = np.linalg.lstsq(A, y, rcond=None)
    err = np.abs(A @ c - y).max() / lsb
    return tuple(float(v) for v in c), float(err)


def fit(f, degree, x_min=-1.0, x_max=1.0, n=4001, lsb=1 / 32768.0):
    """least-squares polynomial c0 + c1 x + ... (Kernel.horner order); returns (coeffs, max |error| in LSB)"""
    x = np.linspace(x_min, x_max, n)
    y = f(x)
    c = np.polynomial.polynomial.polyfit(x, y, degree)
    err = np.abs(np.polynomial.polynomial.polyval(x, c) - y).max() / lsb
    return tuple(float(v) for v in c), float(err)


def scaled_odd(coeffs, s):
    """the same odd polynomial for an input u = x / s (x = s u): a_k s^k"""
    return tuple(c * s ** (2 * i + 1) for i, c in enumerate(coeffs))
