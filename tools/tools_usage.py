"""Write docs/TOOLS.md: every tool of the repository with its usage and parameters.

    python3 tools/tools_usage.py            rewrite docs/TOOLS.md
    python3 tools/tools_usage.py --check    exit code 1 if docs/TOOLS.md is out of date (for tests / CI)

The hand-written guide (docs/TOOLS_GUIDE.md: builds, simulation, checks, install) is copied first; then, for each
Python tool in the directories below, the module docstring and the command-line options found in its argparse calls
(add_argument). Files are read with ast, never imported or run. Build scripts (build.sh) contribute the comment
block at their top or their usage() text.
"""
import ast
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
OUT = os.path.join(ROOT, 'docs', 'TOOLS.md')
GUIDE = os.path.join(ROOT, 'docs', 'TOOLS_GUIDE.md')
DIRS = [
    ('tools', 'Install, containers, firmware, checks'),
    ('asm', 'DSP assembler and disassembler'),
    ('examples/from_scratch/emu', 'Emulator (C core, native code)'),
    ('examples/from_scratch/re', 'DSP research tools (SYSTEM-8)'),
    ('examples/from_scratch/dsp', 'Own DSP program generators (SYSTEM-8)'),
    ('system-1', 'SYSTEM-1 study tools'),
    ('examples/system_1', 'C-S1V4 / C-S1V8 (SYSTEM-1)'),
    ('examples/system_1_synth', 'C-S1SY (SYSTEM-1)'),
    ('examples/system_1_jx', 'C-S1JX (SYSTEM-1)'),
    ('sdk/mport', 'Mutable Instruments port toolkit (docs/MUTABLE_SDK.md)'),
    ('sdk/s1cc/tools', 's1cc glue: kernel placement and emulator check (docs/S1CC.md)'),
    ('examples/mutable_system', 'MUTABLE-SYSTEM (SYSTEM-1)'),
    ('examples/system_s1cc', 'SYSTEM-S1CC: only an s1cc kernel (SYSTEM-1)'),
]


def literal(node):
    try:
        return ast.literal_eval(node)
    except Exception:
        return None


def options(tree):
    """[(flags, help, default)] of the add_argument calls"""
    out = []
    for n in ast.walk(tree):
        if isinstance(n, ast.Call) and getattr(n.func, 'attr', None) == 'add_argument':
            flags = [literal(a) for a in n.args if isinstance(literal(a), str)]
            kw = {k.arg: literal(k.value) for k in n.keywords if k.arg}
            out.append((', '.join(flags), kw.get('help') or '', kw.get('default')))
    return out


def env_vars(src):
    """environment variables read with os.environ.get('NAME', default) / os.environ['NAME']"""
    found = {}
    for m in re.finditer(r"os\.environ\.get\('([A-Z_0-9]+)'(?:,\s*([^)]*))?\)", src):
        found.setdefault(m.group(1), (m.group(2) or '').strip())
    for m in re.finditer(r"os\.environ\['([A-Z_0-9]+)'\]", src):
        found.setdefault(m.group(1), '')
    return found


def py_entry(path):
    src = open(path, encoding='utf-8').read()
    try:
        tree = ast.parse(src)
    except SyntaxError:
        return None
    doc = ast.get_docstring(tree) or ''
    opts = options(tree)
    env = env_vars(src)
    rel = os.path.relpath(path, ROOT)
    L = [f'### `{rel}`', '']
    if doc:
        L += ['```', doc.strip(), '```', '']
    else:
        L += ['(no docstring)', '']
    if opts:
        L += ['| option | help | default |', '|---|---|---|']
        for f, h, d in opts:
            h = str(h).replace('|', '\\|').replace('\n', ' ')
            L.append(f'| `{f}` | {h} | {"" if d is None else "`" + str(d) + "`"} |')
        L.append('')
    if env:
        L += ['Environment: ' + ', '.join(f'`{k}`' + (f' (default {v})' if v else '') for k, v in sorted(env.items())),
              '']
    return '\n'.join(L)


def sh_entry(path):
    src = open(path, encoding='utf-8').read()
    rel = os.path.relpath(path, ROOT)
    m = re.search(r"cat <<'TXT'\n(.*?)\nTXT", src, re.S)
    if m:
        text = m.group(1)
    else:
        lines = []
        for line in src.splitlines()[1:]:
            if not line.startswith('#'):
                break
            lines.append(line[1:].strip())
        text = '\n'.join(lines)
    if not text.strip():
        return None
    return '\n'.join([f'### `{rel}`', '', '```', text.strip(), '```', ''])


def generate():
    parts = []
    if os.path.exists(GUIDE):
        parts.append(open(GUIDE, encoding='utf-8').read().rstrip() + '\n')
    parts += ['', '# Reference (generated by `tools/tools_usage.py`, do not edit by hand)', '']
    for d, title in DIRS:
        full = os.path.join(ROOT, d)
        if not os.path.isdir(full):
            continue
        entries = []
        for name in sorted(os.listdir(full)):
            p = os.path.join(full, name)
            if name.endswith('.py') and not name.startswith(('test_', '__')):
                e = py_entry(p)
            elif name.endswith('.sh'):
                e = sh_entry(p)
            else:
                e = None
            if e:
                entries.append(e)
        if entries:
            parts += [f'## {title} (`{d}/`)', ''] + entries
    return '\n'.join(parts).rstrip() + '\n'


def main():
    text = generate()
    if '--check' in sys.argv:
        old = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        if old != text:
            print('docs/TOOLS.md is out of date: python3 tools/tools_usage.py')
            return 1
        return 0
    open(OUT, 'w', encoding='utf-8').write(text)
    print(f'wrote {os.path.relpath(OUT, ROOT)} ({text.count(chr(10))} lines)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
